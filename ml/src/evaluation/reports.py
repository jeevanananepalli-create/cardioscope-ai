"""Write evaluation results to ml/reports/. Every value comes from a computed result."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Mapping

import pandas as pd

from ml.src.evaluation.metrics import SCALAR_METRICS

COMPARISON_COLUMNS = ("roc_auc", "brier", "accuracy", "balanced_accuracy", "precision", "recall", "f1")


def write_json(path: Path, payload: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def read_json(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


def comparison_table(results: Mapping[str, list[dict[str, Any]]]) -> pd.DataFrame:
    """Flat table: one row per target x candidate with mean and std of each metric."""
    rows = []
    for target, candidates in results.items():
        for result in candidates:
            row = {
                "target": target,
                "candidate": result["candidate"]["name"],
                "algorithm": result["candidate"]["algorithm"],
                "class_weighting": result["candidate"]["class_weighting"],
                "n_folds": result["n_folds"],
            }
            for metric in (*SCALAR_METRICS, "train_roc_auc"):
                row[f"{metric}_mean"] = result["summary"][metric]["mean"]
                row[f"{metric}_std"] = result["summary"][metric]["std"]
            rows.append(row)
    return pd.DataFrame(rows)


def render_comparison_markdown(
    table: pd.DataFrame,
    cv: Mapping[str, Any],
    n_dev: int,
    selection: Mapping[str, Any] | None = None,
) -> str:
    lines = [
        "# Model comparison (cross-validation)",
        "",
        "> Generated by `python -m ml.scripts.compare_models`. Do not edit by hand.",
        "",
        f"Repeated stratified {cv['n_splits']}-fold cross-validation, {cv['n_repeats']} repeats "
        f"({cv['n_splits'] * cv['n_repeats']} folds), on the {n_dev}-record development set. "
        "The holdout set is not used here. Values are mean ± standard deviation across folds, "
        "at a 0.5 decision threshold. `train AUC` is the mean ROC-AUC on the training part of "
        "each fold, shown only to expose overfitting; it is never used for selection.",
        "",
    ]
    for target, group in table.groupby("target", sort=False):
        chosen = selection[target]["selected"] if selection else None
        lines += [
            f"## {target}",
            "",
            "| Candidate | " + " | ".join(COMPARISON_COLUMNS) + " | train AUC |",
            "|---|" + "---|" * (len(COMPARISON_COLUMNS) + 1),
        ]
        for _, row in group.sort_values("roc_auc_mean", ascending=False).iterrows():
            name = f"**{row['candidate']}** (selected)" if row["candidate"] == chosen else row["candidate"]
            cells = [f"{row[f'{m}_mean']:.3f} ± {row[f'{m}_std']:.3f}" for m in COMPARISON_COLUMNS]
            lines.append(f"| {name} | " + " | ".join(cells) + f" | {row['train_roc_auc_mean']:.3f} |")
        if selection:
            lines += ["", f"Selection: {selection[target]['reason']}"]
        lines.append("")
    return "\n".join(lines)
